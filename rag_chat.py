"""
rag_chat.py — RAG-асистент технічної підтримки.

Пайплайн класичний retrieval-augmented generation:
  1. Retrieval: активний бекенд векторного пошуку (vector_store.py) знаходить
     top-k релевантних документів бази знань (з урахуванням рівня допуску
     користувача — фільтрація відбувається до виклику цього модуля).
  2. Augmentation: знайдені фрагменти складаються в контекстний промпт разом
     із коротким профілем користувача (роль/посада/підрозділ), щоб відповідь
     була сформульована практично для конкретної ролі — диспетчеру потрібен
     чіткий порядок дій, HR-менеджеру — посилання на кадрову процедуру,
     електромонтеру — конкретні кроки з технікою безпеки тощо.
  3. Generation: LLM (llm_client.py) генерує відповідь СУВОРО на основі
     наданого контексту, з посиланнями на назви документів.

Якщо LLM не налаштована/недоступна — модуль не "мовчить", а повертає чесну
екстрактивну відповідь, зібрану з найрелевантніших знайдених фрагментів
(без вигадування фактів), з явною позначкою, що це відповідь без LLM.
"""

import re

import llm_client
from vector_store import get_active_backend

BASE_SYSTEM_PROMPT = (
    "Ти — внутрішній технічний асистент енергокомпанії. Відповідай на запитання "
    "співробітників ВИКЛЮЧНО на основі наданого нижче контексту з бази знань "
    "(регламенти, інструкції, паспорти обладнання, схеми, НПАОП, кадрові процедури). "
    "Якщо в контексті немає достатньо інформації для відповіді — чесно скажи про це "
    "і порадь, до якої служби звернутися; не вигадуй факти і не додавай кроків, яких "
    "немає в наданих документах. Відповідай українською мовою. Якщо питання про порядок "
    "дій — відповідай чіткими нумерованими кроками. Обов'язково вказуй, з якого документа "
    "взято кожне твердження, у форматі «[Джерело: назва документа]»."
)

# Короткі рольові інструкції — впливають ТІЛЬКИ на стиль/фокус відповіді,
# не на те, які документи бачить користувач (це вже відфільтровано раніше
# за access_level до виклику цього модуля).
ROLE_HINTS = {
    "employee": "Відповідай практично й по суті, орієнтуючись на польового працівника без глибокого адміністративного контексту.",
    "hr": "Якщо питання кадрове — акцентуй на процедурі, строках і відповідальних службах. Якщо технічне — просто перекажи знайдене.",
    "safety_admin": "Ти спілкуєшся з інженером з охорони праці — можеш вживати терміни ОП без спрощення, посилайся на конкретні пункти НПАОП, якщо вони є в контексті.",
    "admin": "Відповідай вичерпно, це адміністратор системи з повним доступом до бази знань.",
}

URGENT_KEYWORDS = ("аварі", "пожеж", "травм", "ураж", "постражд", "нещасн", "займ")


def _build_context(results):
    blocks = []
    for r in results:
        d = r["doc"]
        blocks.append(f"### Документ: {d['title']} (категорія: {d['category']})\n{d['content']}")
    return "\n\n".join(blocks)


def _build_system_prompt(user):
    if not user:
        return BASE_SYSTEM_PROMPT
    role_hint = ROLE_HINTS.get(user["role"], "")
    profile = (
        f"\n\nКонтекст про користувача, який ставить питання: посада «{user['position']}», "
        f"підрозділ «{user['department']}», філія «{user['branch']}». {role_hint}"
    )
    return BASE_SYSTEM_PROMPT + profile


def _is_urgent(query):
    q = query.lower()
    return any(kw in q for kw in URGENT_KEYWORDS)


def _urgent_banner():
    return (
        "⚠️ **Це питання може стосуватися аварійної ситуації.** Якщо аварія відбувається "
        "просто зараз — насамперед діяйте за встановленим порядком негайного реагування "
        "(повідомте чергового диспетчера, за потреби — 103) і лише потім звіряйтеся з "
        "документацією нижче.\n\n"
    )


def _fallback_answer(query, results):
    """Екстрактивна відповідь без LLM: показуємо найрелевантніші знайдені фрагменти як є."""
    prefix = _urgent_banner() if _is_urgent(query) else ""
    if not results:
        return prefix + (
            "На жаль, у доступній вам базі знань не знайдено документів, що відповідають "
            "на це запитання. Спробуйте переформулювати запит або зверніться до відповідальної служби."
        )
    lines = [
        "*(LLM не налаштована — показую найрелевантніші фрагменти з бази знань без узагальнення LLM.)*",
        "",
    ]
    for r in results:
        d = r["doc"]
        lines.append(f"**{d['title']}** ({d['category']}):")
        lines.append(r["snippet"])
        lines.append(f"_[Джерело: {d['title']}]_")
        lines.append("")
    return prefix + "\n".join(lines)


def answer_query(query, documents, user=None, top_k=4, hidden_count=0):
    """
    documents: список kb_documents (уже відфільтрований за рівнем допуску користувача)
    user: sqlite3.Row поточного користувача — використовується лише для персоналізації
          стилю відповіді (рольовий hint), не впливає на те, які документи доступні.
    hidden_count: скільки документів приховано через рівень допуску — якщо відповідних
          знайдених документів мало/немає, а прихованих багато, попереджаємо користувача.
    Повертає dict: {answer: str, sources: [titles], llm_used: bool}
    """
    backend = get_active_backend()
    results = backend.search(query, documents, category=None, top_k=top_k)
    sources = [r["doc"]["title"] for r in results]

    access_note = ""
    if len(results) < 2 and hidden_count > 0:
        access_note = (
            f"\n\n_Примітка: {hidden_count} документ(и) у базі знань приховано через ваш рівень "
            f"допуску — можливо, повніша відповідь є там. За потреби зверніться до відповідальної служби._"
        )

    if not llm_client.is_llm_configured():
        return {
            "answer": _fallback_answer(query, results) + access_note,
            "sources": sources,
            "llm_used": False,
        }

    context = _build_context(results)
    urgent_hint = "\n\nУВАГА: питання може бути терміновим/аварійним — почни відповідь з короткого нагадування про порядок негайного реагування, якщо це доречно." if _is_urgent(query) else ""
    user_prompt = (
        f"Контекст з бази знань:\n\n{context}\n\n---\n\n"
        f"Запитання співробітника: {query}{urgent_hint}"
    )

    try:
        answer = llm_client.chat_completion(_build_system_prompt(user), user_prompt, max_tokens=700)
        return {"answer": answer + access_note, "sources": sources, "llm_used": True}
    except llm_client.LLMUnavailableError:
        return {
            "answer": _fallback_answer(query, results) + access_note,
            "sources": sources,
            "llm_used": False,
        }

